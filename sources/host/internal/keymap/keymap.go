// Linux input key codes 1..83 share the original Set 1 numbering, with explicit
// exceptions for extended positions. Media keys use Consumer() below.
func Linux(code uint16) (uint16, bool) {
	if k, ok := linuxExtra[code]; ok {
		return k, true
	}
	if code <= 83 {
		return Set1(code, false)
	}
	return 0, false
}

