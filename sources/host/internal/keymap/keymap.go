// Package keymap maps physical key positions to USB HID usages, independently of layout.
package keymap

// Set1 accepts an IBM PC/AT scan code and the extended flag from a Windows LL hook.
// Unsupported keys are ignored, never mapped from a localized character/VK value.
func Set1(scan uint16, extended bool) (uint16, bool) {
	if extended {
		k, ok := extendedSet1[scan]
		return k, ok
	}
	k, ok := set1[scan]
	return k, ok
}

// WindowsBrowserMouseButton maps driver-emitted browser navigation keys to
// the standard XBUTTON1/XBUTTON2 positions used by HID mouse reports.
func WindowsBrowserMouseButton(vk uint32) (uint16, bool) {
	k, ok := map[uint32]uint16{0xa6: 3, 0xa7: 4}[vk]
	return k, ok
}

